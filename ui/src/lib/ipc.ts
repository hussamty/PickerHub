// The only door to Rust. Every call is typed here, so a renamed command fails at build time.
import { invoke } from "@tauri-apps/api/core";
import type { ImageResult, Boot, ColorInfo, Contrast, Frame, NameRow, Op, Palette, Snapshot } from "./types";

export const ipc = {
  boot: () => invoke<Boot>("boot"),
  describe: (hex: string) => invoke<ColorInfo>("describe", { hex }),
  names: (hexes: string[]) => invoke<NameRow[]>("names", { hexes }),
  frame: (hex: string, kind: number) => invoke<Frame>("frame", { hex, kind }),
  fromHsv: (h: number, s: number, v: number) => invoke<string>("from_hsv", { h, s, v }),
  contrast: (fg: string, bg: string) => invoke<Contrast>("contrast", { fg, bg }),
  vision: (hex: string) => invoke<string[]>("vision", { hex }),
  edit: (ops: Op[]) => invoke<Snapshot>("edit", { ops }),
  undo: () => invoke<Snapshot>("undo"),
  redo: () => invoke<Snapshot>("redo"),
  copy: (text: string, raw = false) => invoke<string>("copy", { text, raw }),
  exportPalette: (id: string, format: string) => invoke<string | null>("export_palette", { id, format }),
  exportColors: (name: string, colors: [string, string][], format: string) => invoke<string | null>("export_colors", { name, colors, format }),
  exportText: (name: string, text: string) => invoke<string | null>("export_text", { name, text }),
  semantic: (kind: "css" | "tokens" | "report", themes: Record<string, Record<string, string>>) => invoke<[string, string]>("semantic", { kind, themes }),
  contrastChecks: (roles: Record<string, string>) => invoke<{ foreground: string; background: string; ratio: number; aa: boolean; large: boolean; aaa: boolean }[]>("contrast_checks", { roles }),
  importPalette: (into: string) => invoke<{ palette: Palette; unique: number; duplicates: number } | null>("import_palette", { into }),
  qaReport: (text: string) => invoke<void>("qa_report", { text }),
  supportReport: () => invoke<string | null>("support_report"),
  backupExport: () => invoke<string | null>("backup_export"),
  backupRestore: () => invoke<Snapshot | null>("backup_restore"),
  daily: (action: string, value?: string) => invoke<any>("daily", { action, value }),
  analyzeImage: (bytes: Uint8Array, name: string) => invoke<ImageResult>("analyze_image", bytes, { headers: { "x-name": encodeURIComponent(name) } }),
  analyzeImageFile: () => invoke<ImageResult | null>("analyze_image_file"),
  pick: () => invoke<{ hex: string; copied: string | null; snapshot: Snapshot } | null>("pick"),
  pickMany: (palette: string) => invoke<Snapshot>("pick_many", { palette }),
  trayLabels: (labels: string[]) => invoke<void>("tray_labels", { labels }),
  applyShortcut: (enabled: boolean, shortcut: string, quick: boolean) => invoke<void>("apply_shortcut", { enabled, shortcut, quick }),
  stopSharing: () => invoke<void>("stop_sharing"),
  updateSupported: () => invoke<boolean>("update_supported"),
  updateCheck: () => invoke<{ version: string; current: string; notes: string | null; date: string | null } | null>("update_check"),
  updateInstall: () => invoke<void>("update_install"),
  logTiming: (operation: string, milliseconds?: number) => invoke<void>("log_timing", { operation, milliseconds }),
  startSharing: () => invoke<boolean>("start_sharing"),
  capturePortal: () => invoke<boolean>("capture_portal"),
  sharing: () => invoke<boolean>("sharing"),
  pasteImage: () => invoke<ImageResult>("paste_image"),
};
